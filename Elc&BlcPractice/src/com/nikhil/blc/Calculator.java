package com.nikhil.blc;

public class Calculator {
	

	
	public static int add(int num1, int num2)
	{
	    	int sum=num1+num2;
	    	return sum;
	}
	public static int sub(int x, int y)
	{
		return x-y;
	}
	public static int mul(int x, int y)
	{
		return x*y;
	}
	public static double div(int x, int y)
	{
		return x/y;
	}
}
